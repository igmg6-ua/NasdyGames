def _medal(size, emblem, locked=False):
    import math
    c = (size - 1) / 2
    r_out = size / 2
    rows = []
    e0 = (size - len(emblem)) // 2
    for y in range(size):
        row = ''
        for x in range(size):
            d = math.hypot(x - c, y - c)
            if d > r_out - 0.2:
                row += '.'
                continue
            if locked:
                row += '3' if d > r_out - 1.2 else '2'
                continue
            ang = math.degrees(math.atan2(y - c, x - c)) % 360
            if size >= 32:
                if d > r_out - 1.2:
                    ch = '3'
                elif d > r_out - 3.2:          # borde con cuentas
                    ch = '1' if int(ang) % 30 < 8 else '2'
                    if 200 < ang < 250:
                        ch = '1'               # brillo arriba a la izquierda
                elif d > r_out - 4.2:
                    ch = '3'
                else:
                    ch = '1'
            else:
                if d > r_out - 1.2:
                    ch = '3'
                elif d > r_out - 2.4:
                    ch = '2'
                else:
                    ch = '1'
            ey, ex = y - e0, x - e0
            if ch == '1' and 0 <= ey < len(emblem) and 0 <= ex < len(emblem):
                if emblem[ey][ex] == '3':
                    ch = '3'
            row += ch
        rows.append(row)
    return rows


MEDAL_BIG = _medal(32, _MAZE_EMBLEM)                     # 32 x 32 (sprites)
MEDAL_SMALL = _medal(16, _MAZE_EMBLEM_SMALL)             # 16 x 16 (fondo)
MEDAL_LOCKED = _medal(16, _MAZE_EMBLEM_SMALL, locked=True)


def medal_spin_frames():
    """Las imágenes del medallón girando: de frente a de canto.
    Cada una es el dibujo encogido en horizontal (32, 26, 18, 10 y 4 píxeles
    de ancho), centrado. La de canto es una barra con el grosor de la moneda."""
    frames = []
    for w in (32, 26, 18, 10):
        x0 = (32 - w) // 2
        rows = []
        for y in range(32):
            row = ['.'] * 32
            for x in range(w):
                sx = int((x + 0.5) * 32 / w)
                ch = MEDAL_BIG[y][sx]
                if w < 32 and ch == '1' and x < w // 3:
                    ch = '2'               # sombra: la cara que se aleja
                row[x0 + x] = ch
            rows.append(''.join(row))
        frames.append(rows)
    rows = []
    for y in range(32):
        row = ['.'] * 32
        if MEDAL_BIG[y][16] != '.':
            for k, ch in enumerate('3123'):
                row[14 + k] = ch
        rows.append(''.join(row))
    frames.append(rows)
    return frames



def check():
    """Comprueba el tamaño de todos los dibujos."""
    bad = []
    for name, frames in CHARACTERS + OBJECTS:
        for fname, rows in frames:
            if len(rows) != 16 or any(len(r) != 16 for r in rows):
                bad.append((name, fname, [len(r) for r in rows]))
    if len(CURSOR) != 16 or any(len(r) != 8 for r in CURSOR):
        bad.append(('CURSOR', '', [len(r) for r in CURSOR]))
    for name, rows in BG_FLOOR + BG_HUD + BG_SOLID:
        if len(rows) != 8 or any(len(r) != 8 for r in rows):
            bad.append((name, '', [len(r) for r in rows]))
    return bad


